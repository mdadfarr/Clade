import { contextBridge, ipcRenderer, webUtils } from 'electron';

// Chat calls name their pane (each pane is one chat with its own claude); messages for a pane come back
// with its id first. '' means the focused pane.
contextBridge.exposeInMainWorld('api', {
  appStart: () => ipcRenderer.invoke('app-start'),
  paneOpen: (pane: string, o: unknown) => ipcRenderer.send('pane-open', pane, o),
  paneClose: (pane: string) => ipcRenderer.send('pane-close', pane),
  paneFocus: (pane: string) => ipcRenderer.send('pane-focus', pane),
  makeBranch: (pane: string) => ipcRenderer.invoke('make-branch', pane),
  saveWorkspace: (ws: unknown) => ipcRenderer.send('workspace-save', ws),
  onPaneTitles: (cb: (t: unknown) => void) => ipcRenderer.on('pane-titles', (_e, t) => cb(t)),
  onPaneModes: (cb: (pane: string, mode: string | null, effort: string | null) => void) => ipcRenderer.on('pane-modes', (_e, p, m, f) => cb(p, m, f)),
  onFocusPane: (cb: (pane: string) => void) => ipcRenderer.on('focus-pane', (_e, p) => cb(p)),
  write: (pane: string, data: string) => ipcRenderer.send('pty-write', pane, data),
  resize: (pane: string, cols: number, rows: number) => ipcRenderer.send('pty-resize', pane, cols, rows),
  send: (pane: string, text: string) => ipcRenderer.send('chat-send', pane, text),
  onChat: (cb: (pane: string, chat: unknown) => void) => ipcRenderer.on('chat', (_e, p, c) => cb(p, c)),
  branch: (pane: string, replyId?: string, from?: string) => ipcRenderer.send('branch', pane, replyId, from),
  retry: (pane: string, replyId: string) => ipcRenderer.send('retry', pane, replyId),
  edit: (pane: string, replyId: string, text: string) => ipcRenderer.send('edit', pane, replyId, text),
  copy: (text: string) => ipcRenderer.send('copy', text),
  onNote: (cb: (pane: string, text: string) => void) => ipcRenderer.on('note', (_e, p, t) => cb(p, t)),
  onPrefill: (cb: (pane: string, text: string, why?: string) => void) => ipcRenderer.on('prefill', (_e, p, t, w) => cb(p, t, w)),
  openSession: (pane: string, id: string) => ipcRenderer.send('open-session', pane, id),
  onGraph: (cb: (pane: string, graph: unknown) => void) => ipcRenderer.on('graph', (_e, p, g) => cb(p, g)),
  onToggleGraph: (cb: () => void) => ipcRenderer.on('toggle-graph', () => cb()),
  onTermReset: (cb: (pane: string) => void) => ipcRenderer.on('term-reset', (_e, p) => cb(p)),
  onToggleTerm: (cb: () => void) => ipcRenderer.on('toggle-term', () => cb()),
  onData: (cb: (pane: string, data: string) => void) => ipcRenderer.on('pty-data', (_e, p, d) => cb(p, d)),
  onCards: (cb: (pane: string, cards: unknown) => void) => ipcRenderer.on('cards', (_e, p, c) => cb(p, c)),
  onShowTerm: (cb: (pane: string, why: string) => void) => ipcRenderer.on('show-term', (_e, p, w) => cb(p, w)),
  onCheckQuestion: (cb: (pane: string) => void) => ipcRenderer.on('check-question', (_e, p) => cb(p)),
  wheelLog: process.argv.includes('--wheel-log'),
  logWheel: (line: string) => ipcRenderer.send('wheel-log', line),
  answerCard: (id: string, answer: unknown) => ipcRenderer.send('card-answer', id, answer),
  onDesign: (cb: (design: unknown, error: string | null, info: string | null, theme: string, looks: unknown) => void) =>
    ipcRenderer.on('design', (_e, d, err, info, theme, looks) => cb(d, err, info, theme, looks)),
  onChats: (cb: (chats: unknown) => void) => ipcRenderer.on('chats', (_e, c) => cb(c)),
  newChat: (pane: string) => ipcRenderer.send('new-chat', pane),
  renameChat: (id: string, name: string) => ipcRenderer.send('rename-chat', id, name),
  // message box controls
  pathOf: (file: File) => webUtils.getPathForFile(file), // the path of a dropped file; the file itself is not read
  pickFiles: () => ipcRenderer.invoke('pick-files'),
  statFiles: (paths: string[]) => ipcRenderer.invoke('stat-files', paths),
  savePaste: (bytes: Uint8Array, mime: string) => ipcRenderer.invoke('save-paste', bytes, mime),
  stop: (pane: string) => ipcRenderer.send('stop', pane),
  stopScreen: (pane: string, lines: string[]) => ipcRenderer.send('stop-screen', pane, lines),
  setOptions: (pane: string, patch: unknown) => ipcRenderer.send('set-options', pane, patch),
  nextMode: (pane: string) => ipcRenderer.send('next-mode', pane),
  zoom: (dir: number) => ipcRenderer.send('zoom', dir),
  onSettings: (cb: (s: unknown) => void) => ipcRenderer.on('settings', (_e, s) => cb(s)),
  onShortcut: (cb: (name: string) => void) => ipcRenderer.on('shortcut', (_e, n) => cb(n)),
  skillsList: () => ipcRenderer.invoke('skills-list'),
  skillSwitch: (name: string, on: boolean) => ipcRenderer.invoke('skill-switch', name, on),
  skillAdd: () => ipcRenderer.invoke('skill-add'),
  designSet: (patch: unknown) => ipcRenderer.send('design-set', patch),
  onAccount: (cb: (a: unknown) => void) => ipcRenderer.on('account', (_e, a) => cb(a)),
  accountRefresh: () => ipcRenderer.send('account-refresh'),
  showUsage: (pane: string) => ipcRenderer.send('show-usage', pane),
  usageOpen: (pane: string) => ipcRenderer.invoke('usage-open', pane),
  usageClose: () => ipcRenderer.send('usage-close'),
  saveDrawing: (svg: string, name: string) => ipcRenderer.send('save-drawing', svg, name),
  openSource: () => ipcRenderer.send('open-source'),
  helpText: () => ipcRenderer.invoke('help-text'),
  appVersion: () => ipcRenderer.invoke('app-version'),
  resetDesign: () => ipcRenderer.send('reset-design'),
  openFolder: () => ipcRenderer.send('open-folder'),
  openArtifact: (name: string, version?: number) => ipcRenderer.send('artifact-open', name, version),
  stepArtifact: (delta: number) => ipcRenderer.send('artifact-step', delta),
  reloadArtifact: () => ipcRenderer.send('artifact-reload'),
  closeArtifact: () => ipcRenderer.send('artifact-close'),
  revealArtifact: () => ipcRenderer.send('artifact-reveal'),
  artifactBounds: (b: unknown) => ipcRenderer.send('artifact-bounds', b),
  onArtifacts: (cb: (list: unknown) => void) => ipcRenderer.on('artifacts', (_e, l) => cb(l)),
  onArtifactShown: (cb: (shown: unknown) => void) => ipcRenderer.on('artifact-shown', (_e, s) => cb(s)),
});
