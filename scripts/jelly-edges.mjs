// Writes src/jelly-edges.ts: for every frame of the jellyfish video, the lowest pixel row that is not black
// (the video's background is pure black, so any lit pixel is jellyfish). The dive (renderer.ts) uses it to
// know when the last visible part of the jellyfish has left the view. Run again after replacing the video:
//   node scripts/jelly-edges.mjs
import { spawn, execFileSync } from 'child_process';
import fs from 'fs';
const file = 'assets/jellyfish/clade-jellyfish-mono.mp4';
const THRESHOLD = 8; // 0-255: dimmer than this counts as black
const probe = JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height,r_frame_rate', '-of', 'json', file], { encoding: 'utf8' })).streams[0];
const [num, den] = probe.r_frame_rate.split('/').map(Number);
const W = probe.width, H = probe.height, N = W * H;
const p = spawn('ffmpeg', ['-v', 'error', '-i', file, '-f', 'rawvideo', '-pix_fmt', 'gray', '-']);
let buf = Buffer.alloc(0);
const bottom = [];
p.stdout.on('data', (d) => {
  buf = Buffer.concat([buf, d]);
  while (buf.length >= N) {
    const fr = buf.subarray(0, N);
    buf = buf.subarray(N);
    let b = -1;
    for (let y = H - 1; y >= 0 && b < 0; y--) for (let x = 0, row = y * W; x < W; x++) if (fr[row + x] >= THRESHOLD) { b = y; break; }
    bottom.push(b);
  }
});
p.on('close', (code) => {
  if (code !== 0 || !bottom.length) throw new Error('ffmpeg failed');
  fs.writeFileSync('src/jelly-edges.ts', `// Generated by scripts/jelly-edges.mjs from ${file}: do not edit.
// bottom[i]: the lowest row (0 = top) with jellyfish in frame i, in video pixels; -1 = an empty frame.
// Plain script: loaded by index.html (a global) and by the tests through require().
const JELLY_EDGES = { width: ${W}, height: ${H}, fps: ${num / den}, bottom: [${bottom.join(', ')}] };
if (typeof module !== 'undefined') module.exports = { JELLY_EDGES };
`);
  console.log(`src/jelly-edges.ts: ${bottom.length} frames, bottom rows ${Math.min(...bottom)}-${Math.max(...bottom)}`);
});
